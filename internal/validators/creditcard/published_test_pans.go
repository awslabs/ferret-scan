// publishedTestPANBlocks holds the card numbers payment processors publish for their sandboxes:
// every Luhn-valid 13-, 14-, 15-, 16- or 19-digit number the page named on each block prints as a
// test card, copied digit for digit (#883).
//
// GENERATED DATA, not hand-maintained. Each block records the page it was read from and the date
// it was read, so a reviewer can tell how stale a block is without fetching anything.
//
// # What is admitted
//
// A value is admitted only when all of these hold:
//   - a processor's or card network's own testing page lists it, and the block cites that page;
//   - it passes Luhn and has 13, 14, 15, 16 or 19 digits, the lengths ValidateContent reports;
//   - it is not a genuine-card positive of the golden or score corpus. If a vendor ever lists
//     one, replace the fixture; do not exempt the value.
//
// Values that are merely common in tutorials, card-generator output or aggregator lists are NOT
// admitted. Popularity in documentation is not publication as a test value, and that confusion is
// how a list in the bank-account validator came to hold two live routing numbers (#628). A value
// found only on a page its vendor no longer publishes waits until a current page lists it. A
// number a page prints that fails Luhn is left out and noted on its block: the validator never
// reports a Luhn-failing candidate, so listing it would be dead.
//
// # What a listed value does
//
// It is capped, never dropped. ValidateContent still reports it, so redaction still rewrites it,
// at no more than testValueCeiling (15, LOW) with not_test=false, and publishes that ceiling so the
// document bridge cannot lift it back after its own adjustment. A wrong entry therefore costs
// rank, not redaction. The lookup is an exact match on the candidate's digits, so nothing in the
// scanned content can steer it: an author cannot turn a real card into a listed one.
//
// # Refreshing
//
// Re-read each page, copy every number its test-card tables print, keep the Luhn-valid ones of
// an admitted length, sort the block and update retrieved. docs.stripe.com/testing renders its
// tables from Markdoc data embedded in the page: read the number attribute of every CardNumber
// node. TestPublishedTestPANsAreWellFormed checks the digits, length, Luhn, order and duplicates
// of every block, and its https:// URL and ISO date.

// publishedTestPANBlock is the test numbers one vendor page publishes.
type publishedTestPANBlock struct {
	vendor    string
	url       string   // the page the values were copied from
	retrieved string   // the ISO 8601 date the page was read
	pans      []string // digits only, sorted, no duplicates
}

// publishedTestPANSet is every block's values in one set. Built once at init: NewValidator hands it
// to each Validator, and the lookup runs once per Luhn-valid candidate.
var publishedTestPANSet = func() map[string]struct{} {
	set := make(map[string]struct{})
	for _, b := range publishedTestPANBlocks {
		for _, p := range b.pans {
			set[p] = struct{}{}
		}
	}
	return set
}()

